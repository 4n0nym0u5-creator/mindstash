export const ideas: Idea[] = [...narcissismIdeas, ...coreIdeas];

export function getIdea(id: string) {
  return ideas.find((i) => i.id === id);
}

export function ideasByTopic(topicId: string) {
  return ideas.filter((i) => i.topicIds.includes(topicId));
}

export function relatedIdeas(idea: Idea, limit = 4) {
  return ideas
    .filter(
      (i) =>
        i.id !== idea.id &&
        i.topicIds.some((t) => idea.topicIds.includes(t)),
    )
    .slice(0, limit);
}
